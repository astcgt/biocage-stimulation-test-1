#!/usr/bin/env python3
"""h52: build the Claude Code subagent files from one core + per-tier patches.

Source:  human_study/agent_prompts/<agent>/{meta.json, core.md, patch-*.md}
Output:  .claude/agents/<variant name>.md  (frontmatter + generated note + parts joined)

Usage:   python scripts/8_audit/h52_agent_prompts.py           # write the agent files
         python scripts/8_audit/h52_agent_prompts.py --check   # compare only; exit 1 on drift
h37 R18 calls check() so a hand-edited or stale agent file is a FAIL.
"""
import json, os, sys

P = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(P, 'human_study/agent_prompts')
OUT = os.path.join(P, '.claude/agents')
NOTE = '<!-- generated by scripts/8_audit/h52_agent_prompts.py from human_study/agent_prompts/{agent}/ ({parts}); edit the sources, then rerun h52 -->'


def render():
    """Return {output path: expected text} for every variant of every agent."""
    files = {}
    for agent in sorted(os.listdir(SRC)):
        d = os.path.join(SRC, agent)
        if not os.path.isfile(os.path.join(d, 'meta.json')): continue
        meta = json.load(open(os.path.join(d, 'meta.json')))
        for v in meta['variants']:
            head = ['---', f"name: {v['name']}", f"description: {v['description']}", f"tools: {meta['tools']}"]
            if v.get('model') and v['model'] != 'inherit': head.append(f"model: {v['model']}")
            head.append('---')
            body = [open(os.path.join(d, part)).read().strip() for part in v['parts']]
            text = '\n'.join(head) + '\n\n' + NOTE.format(agent=agent, parts=' + '.join(v['parts'])) + '\n\n' + '\n\n'.join(body) + '\n'
            files[os.path.join(OUT, v['name'] + '.md')] = text
    return files


def check():
    """List of (path, problem) for agent files that differ from the sources."""
    bad = []
    for path, text in render().items():
        rel = os.path.relpath(path, P)
        if not os.path.exists(path): bad.append((rel, 'missing'))
        elif open(path).read() != text: bad.append((rel, 'differs from sources (hand-edited or not regenerated)'))
    return bad


if __name__ == '__main__':
    if '--check' in sys.argv:
        bad = check()
        for rel, why in bad: print(f'DRIFT {rel}: {why}')
        print('agent prompts in sync' if not bad else f'{len(bad)} agent file(s) out of sync')
        sys.exit(1 if bad else 0)
    os.makedirs(OUT, exist_ok=True)
    for path, text in render().items():
        open(path, 'w').write(text); print('wrote', os.path.relpath(path, P))
